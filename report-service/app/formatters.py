"""
Report Formatters (Markdown and JSON).
"""
import json
from typing import Dict, Any


class ReportFormatter:
    @staticmethod
    def to_markdown(report_dict: Dict[str, Any]) -> str:
        status_icon = "🟢" if report_dict["status"] == "PASSED" else ("🟡" if report_dict["status"] == "DEGRADED" else "🔴")
        rto_icon = "✅" if report_dict.get("rto_met", True) else "❌"
        rpo_icon = "✅" if report_dict.get("rpo_met", True) else "❌"

        lines = [
            f"# CloudGuard Recovery Drill Report",
            f"**Test ID**: `{report_dict['test_id']}`  ",
            f"**Application**: `{report_dict['application_name']}`  ",
            f"**Status**: {status_icon} **{report_dict['status']}**  ",
            "",
            "## Executive Summary",
            f"> {report_dict['summary']}",
            "",
            "## Service Level Agreements (SLAs)",
            "| Metric | Target | Measured | Compliance |",
            "|---|---|---|---|",
            f"| **Recovery Time Objective (RTO)** | < {report_dict.get('target_rto_seconds', 300):.1f}s | {report_dict.get('rto_seconds', 0):.2f}s | {rto_icon} |",
            f"| **Recovery Point Objective (RPO)** | < {report_dict.get('target_rpo_minutes', 60):.1f}m | {report_dict.get('rpo_minutes', 0):.2f}m | {rpo_icon} |",
            "",
        ]

        findings = report_dict.get("findings", [])
        if findings:
            lines.append("## Findings & Discrepancies")
            for f in findings:
                lines.append(f"- ⚠️ {f}")
            lines.append("")

        lines.append("---")
        lines.append("*Generated by CloudGuard V1 Disaster Recovery Monitoring Engine.*")
        return "\n".join(lines)

    @staticmethod
    def to_json(report_dict: Dict[str, Any]) -> str:
        return json.dumps(report_dict, indent=2)
